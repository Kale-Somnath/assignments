//1. primitive data types  =>Immutable data types ->cant change the original value
//2. Non premitive data types =>Mutable data type ->Meaning the original value can be modified

//Immutable data types
let a=10;
a+10;
console.log(a);

//Mutable data type
let empData={
    "name":"Somnath",
    "id":1234
}
empData.age=35;
console.log(empData);

